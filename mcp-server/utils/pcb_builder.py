ROOT = Path(__file__).resolve().parents[1]

CATALOG_DIR = ROOT / 'catalog'
_catalog_cache: dict = {}

def _read_json_file(name):
    """Parse a catalog JSON file once per modification time; a missing file is empty."""
    path = CATALOG_DIR / name
    try:
        info = path.stat()
    except FileNotFoundError:
        return (None, {})
    stamp = (info.st_mtime_ns, info.st_size)
    cached = _catalog_cache.get(name)
    if cached is None or cached[0] != stamp:
        _catalog_cache[name] = cached = (stamp, json.loads(path.read_text()))
    return cached

def _tier(parts, tier):
    return {pid: {**part, 'tier': part.get('tier', tier)} for pid, part in parts.items()}

def load_curated_catalog():
    """Hand-reviewed parts only (curated_parts.json), with sourcing applied."""
    return _merged_catalog()[0]

def load_catalog():
    """Curated parts plus parts generated by scripts/import_kicad.py (curated ids always win), with the LCSC
    codes and prices from sourcing.json (scripts/refresh_sourcing.py) applied to both tiers."""
    return _merged_catalog()[1]

def _merged_catalog():
    files = [_read_json_file(n) for n in ('curated_parts.json', 'imported_parts.json', 'sourcing.json')]
    key = tuple(stamp for stamp, _ in files)
    cached = _catalog_cache.get('_merged')
    if cached is None or cached[0] != key:
        curated, imported, overlay = (data for _, data in files)
        curated, imported = _tier(curated, 'curated'), _tier(imported, 'imported')
        def apply(parts):
            out = {}
            for pid, part in parts.items():
                update = overlay.get(pid) if not pid.startswith('_') else None
                if update:
                    part = {**part, **{k: update[k] for k in ('lcsc', 'price_usd') if k in update}, 'sourcing': update['sourcing']}
                out[pid] = part
            return out
        curated, imported = apply(curated), apply(imported)
        _catalog_cache['_merged'] = cached = (key, curated, {**imported, **curated})
    return cached[1], cached[2]

def finite(value, name, minimum=None, maximum=None):
    if isinstance(value, bool):
        raise ValueError(f'{name} must be a number')
    try:
        n = float(value)
    except (ValueError, TypeError):
        raise ValueError(f'{name} must be a finite number') from None
    if not math.isfinite(n) or (minimum is not None and n < minimum) or (maximum is not None and n > maximum):
        raise ValueError(f'{name} is outside supported limits')
    return n

def normalize_design(components, nets, board_width_mm=50, board_height_mm=40, auto_place=None, requirements=None,
                     layer_count=None, stackup=None, netclasses=None, fabricator_profile=None):
    """Validate and normalize a design.

    layer_count defaults to the stackup's copper count (2 when neither is given).
    netclasses (optional) and fabricator_profile (default 'conservative') resolve to
    design['netclasses'] (see utils/netclasses.py) and the KiCad design rules in board.kicad_pro.

    auto_place: None (default) auto-places only components missing x_mm or y_mm (or with
    null coordinates); components with explicit coordinates stay fixed and act as
    obstacles. True ignores all supplied coordinates/rotations and places everything.
    False disables auto-placement (legacy 8 mm grid for missing coordinates).
    Refs that were placed by the server are listed in design['auto_placed'].
    """
    from .placement import auto_place as _auto_place, normalize_cluster_metadata, resolve_clusters, inspect_clusters
    from .stackups import resolve_stackup
    layer_count, stackup = resolve_stackup(layer_count, stackup)
    from .fab_profiles import resolve_profile
    fabricator_profile = resolve_profile(fabricator_profile, layer_count)
    width = finite(board_width_mm, 'board_width_mm', 5, 300)
    height = finite(board_height_mm, 'board_height_mm', 5, 300)
    if not isinstance(components, list) or not 1 <= len(components) <= 200:
        raise ValueError('components must contain 1 to 200 entries')
    if not isinstance(nets, list) or len(nets) > 500:
        raise ValueError('nets must be a list of at most 500 entries')
    cat, refs, cs, warnings = load_catalog(), {}, [], []
    movable = set()
    for i, c in enumerate(components):
        if not isinstance(c, dict):
            raise ValueError('each component must be an object')
        ref, pid = c.get('ref'), c.get('part_id')
        if not isinstance(ref, str) or not re.fullmatch(r'[A-Za-z][A-Za-z0-9_]{0,31}', ref):
            raise ValueError('component reference must start with a letter and contain only letters, numbers, underscores')
        if ref in refs:
            raise ValueError(f'duplicate reference {ref}')
        if pid not in cat:
            raise ValueError(f'unknown part_id {pid!r}; call list_curated_parts')
        p = cat[pid]
        value = c.get('value', pid)
        if not isinstance(value, str) or len(value) > 120 or any(ord(ch)<32 for ch in value):
            raise ValueError(f'invalid value for {ref}')
        missing = c.get('x_mm') is None or c.get('y_mm') is None
        if auto_place is not False and (missing or auto_place is True):
            movable.add(ref)
        x = finite((width/2 if ref in movable else 8 + (i % 5)*8) if c.get('x_mm') is None else c['x_mm'], f'{ref}.x_mm', 0, width)
        y = finite((height/2 if ref in movable else 8 + (i // 5)*8) if c.get('y_mm') is None else c['y_mm'], f'{ref}.y_mm', 0, height)
        rot = finite(c.get('rotation_deg') or 0, f'{ref}.rotation_deg') % 360
        normalized = {'ref':ref, 'part_id':pid, 'value':value, 'x_mm':x, 'y_mm':y, 'rotation_deg':rot}
        nc = c.get('nc_pins', [])
        if not isinstance(nc, list) or any(not isinstance(pin, str) for pin in nc):
            raise ValueError(f'{ref}.nc_pins must be a list of pin numbers or names')
        canonical_nc = []
        for pin in nc:
            matches = [p['number'] for p in cat[pid]['pins'] if p['number'] == pin]
            if not matches:
                matches = [p['number'] for p in cat[pid]['pins'] if p['name'].upper() == pin.upper()]
            if not matches:
                raise ValueError(f'unknown no-connect pin {ref}.{pin}')
            canonical_nc.extend(number for number in matches if number not in canonical_nc)
        if canonical_nc:
            normalized['nc_pins'] = canonical_nc
        if 'current_draw_ma' in c:
            normalized['current_draw_ma'] = finite(c['current_draw_ma'], f'{ref}.current_draw_ma', 0, 1e6)
        if 'tolerance_pct' in c:
            tolerance = finite(c['tolerance_pct'], f'{ref}.tolerance_pct', 0, 100)
            if tolerance == 100:
                raise ValueError(f'{ref}.tolerance_pct must be less than 100')
            normalized['tolerance_pct'] = tolerance
        if 'sourcing' in c:
            normalized['sourcing'] = normalize_sourcing(c['sourcing'], normalized, p)
            if 'tolerance_pct' not in normalized and 'tolerance_pct' in normalized['sourcing']:
                normalized['tolerance_pct'] = normalized['sourcing']['tolerance_pct']
        from .placement_constraints import normalize_bypass_metadata
        normalize_bypass_metadata(c, normalized)
        normalize_cluster_metadata(c, normalized)
        cs.append(normalized); refs[ref] = normalized
    used, ns, names = {}, [], set()
    for net in nets:
        if not isinstance(net, dict):
            raise ValueError('each net must be an object')
        name = net.get('name')
        if not isinstance(name, str) or not re.fullmatch(r'[A-Za-z0-9_+./:-]{1,64}', name):
            raise ValueError('net name contains unsupported characters')
        if name in names:
            raise ValueError(f'duplicate net {name}')
        names.add(name)
        connections = net.get('connections')
        if not isinstance(connections, list) or not connections:
            raise ValueError(f'net {name} needs connections')
        resolved = []
        for conn in connections:
            if not isinstance(conn, str) or '.' not in conn:
                raise ValueError(f'invalid connection {conn!r}')
            ref, pin = conn.split('.', 1)
            if ref not in refs:
                raise ValueError(f'unknown component {ref}')
            pins = cat[refs[ref]['part_id']]['pins']
            matched = [p['number'] for p in pins if p['number'] == pin]
            if not matched:
                matched = [p['number'] for p in pins if p['name'].upper() == pin.upper()]
            if not matched:
                raise ValueError(f'unknown pin {conn}')
            for number in matched:
                canonical = f'{ref}.{number}'
                if canonical in used and used[canonical] != name:
                    raise ValueError(f'{canonical} is assigned to both {used[canonical]} and {name}')
                used[canonical] = name
                if canonical not in resolved:
                    resolved.append(canonical)
        normalized_net = {'name':name,'connections':resolved}
        if 'voltage_v' in net:
            normalized_net['voltage_v'] = finite(net['voltage_v'], f'{name}.voltage_v', -1000, 1000)
        if 'max_current_ma' in net:
            normalized_net['max_current_ma'] = finite(net['max_current_ma'], f'{name}.max_current_ma', 0, 1e6)
        ns.append(normalized_net)
    from .netclasses import validate_input
    netclass_input = validate_input(netclasses, names)
    for c in cs:
        for pin in cat[c['part_id']]['pins']:
            canonical = f"{c['ref']}.{pin['number']}"
            if pin['number'] in c.get('nc_pins', []):
                if canonical in used:
                    raise ValueError(f'{canonical} is marked no-connect but assigned to a net')
                continue
            if canonical not in used:
                warnings.append(f"Unassigned pin {c['ref']}.{pin['number']} ({pin['name']})")
    from .placement_constraints import resolve_bypasses, inspect_placement
    bypasses, placement_issues = resolve_bypasses(cs, ns)
    clusters = resolve_clusters(cs)
    auto_placed = _auto_place(cs, ns, cat, width, height, movable, bypass_constraints=bypasses, clusters=clusters) if movable else []
    design = {'components':cs,'nets':ns,'auto_placed':auto_placed,'board_width_mm':width,'board_height_mm':height,
              'layer_count':layer_count,'stackup':stackup,'warnings':warnings,
              'bom':[bom_entry(c, cat[c['part_id']]) for c in cs]}
    if any(c['part_id'] in ('R','C') and not item['lcsc'] for c, item in zip(cs, design['bom'])):
        warnings.append('Resistor and capacitor LCSC codes are left blank: select orderable parts matching each value, rating and tolerance before assembly')
    imported = sorted({c['part_id'] for c in cs if cat[c['part_id']].get('tier') == 'imported'})
    if imported:
        warnings.append(f"Imported KiCad parts {imported} are not hand-reviewed: verify pinout, footprint and ratings against the datasheet")
    from .footprint_check import load_footprint_checks
    checks = load_footprint_checks()
    mismatched = sorted({c['part_id'] for c in cs if (checks.get(c['part_id']) or {}).get('status') == 'mismatch'})
    if mismatched:
        worst = ', '.join(f"{pid} ({checks[pid]['worst_delta_mm']} mm)" if checks[pid].get('worst_delta_mm') is not None else pid for pid in mismatched)
        warnings.append(f"Footprint of {mismatched} differs from the footprint of its sourced LCSC part (worst pad delta: {worst}); compare the land pattern with the exact part's drawing")
    unsourced = sorted({c['part_id'] for c in cs if c['part_id'] not in ('R', 'C') and not cat[c['part_id']].get('lcsc')})
    if unsourced:
        warnings.append(f"No LCSC code for {unsourced}: choose an orderable part matching the value and footprint before assembly (BOM cost excludes them)")
    if any(c.get('sourcing') for c in cs):
        warnings.append('Sourcing details are declarations only; verify supplier availability and exact value, footprint, rating and tolerance before assembly')
    for pad in pad_positions(design):
        if not (0 < pad['x_mm']-pad['radius_mm'] and pad['x_mm']+pad['radius_mm'] < width and 0 < pad['y_mm']-pad['radius_mm'] and pad['y_mm']+pad['radius_mm'] < height):
            raise ValueError(f"{pad['connection']} pad extends beyond the board edge; adjust placement")
    if requirements is not None:
        from .requirements import normalize_requirements
        design['requirements'] = normalize_requirements(requirements, width, height)
    design['placement_checks'] = inspect_placement(cs, ns, cat, bypasses, placement_issues)
    warnings.extend(item['message'] for item in design['placement_checks']['issues'])
    if clusters:
        design['cluster_checks'] = inspect_clusters(cs, cat, clusters)
        warnings.extend(item['message'] for item in design['cluster_checks']['issues'])
    from .electrical import inspect_electrical
    design['electrical_checks'], design['power_budget'] = inspect_electrical(design, cat)
    design['footprint_reviews'] = [{'component': c['ref'], 'part_id': c['part_id'], 'cross_check': (checks.get(c['part_id']) or {}).get('status', 'missing'), **cat[c['part_id']].get('footprint_review', {'status': 'unreviewed', 'manufacturer_drawing': None})} for c in cs]
    warnings.extend(item['message'] for item in design['electrical_checks']['issues'])
    from .netclasses import resolve as resolve_netclasses
    design['fabricator_profile'] = fabricator_profile
    design['netclass_input'] = netclass_input
    design['netclasses'], netclass_warnings = resolve_netclasses(design, cat, design['netclass_input'], fabricator_profile)
    warnings.extend(netclass_warnings)
    return design

def pad_positions(design):
    cat = load_catalog()
    lookup = {p:n['name'] for n in design['nets'] for p in n['connections']}
    pads = []
    for c in design['components']:
        # KiCad's positive angles rotate counterclockwise in screen coordinates.
        a = math.radians(c['rotation_deg']); co, si = math.cos(a), math.sin(a)
        for pad in cat[c['part_id']]['pads']:
            x, y = pad['x_mm'], pad['y_mm']
            conn = f"{c['ref']}.{pad['number']}"
            pads.append({**pad, 'connection':conn, 'net':lookup.get(conn), 'x_mm':c['x_mm']+x*co+y*si, 'y_mm':c['y_mm']-x*si+y*co, 'radius_mm':math.hypot(pad['width_mm'],pad['height_mm'])/2})
    return pads

def q(value):
    return json.dumps(str(value), ensure_ascii=False)

def _atomic_bytes(destination, payload):
    destination = Path(destination)
    temp = None
    try:
        with tempfile.NamedTemporaryFile('wb', dir=destination.parent, prefix='.' + destination.name, suffix='.eea-tmp', delete=False) as stream:
            temp = Path(stream.name)
            stream.write(payload)
        os.replace(temp, destination)
    except BaseException:
        if temp is not None:
            temp.unlink(missing_ok=True)
        raise


def write_board(design, destination, segments=None, zones=''):
    catalog = load_catalog()
    codes = {n['name']:i+1 for i,n in enumerate(design['nets'])}
    assignments = {p:n['name'] for n in design['nets'] for p in n['connections']}
    from .stackups import header_lines
    lines = ['(kicad_pcb (version 20221018) (generator eea)', *header_lines(design), ' (net 0 "")']
    lines.extend(f' (net {code} {q(name)})' for name,code in codes.items())
    for c in design['components']:
        part = catalog[c['part_id']]
        fp = part['footprint_sexpr']
        fp = fp.replace('(layer "F.Cu")', f'(layer "F.Cu") (at {c["x_mm"]:g} {c["y_mm"]:g} {c["rotation_deg"]:g})', 1)
        # KiCad stores pad angles as absolute, so pads must carry the footprint rotation too.
        if c['rotation_deg'] % 360:
            fp = re.sub(r'(\(pad "[^"\n]+" (?:smd|thru_hole|np_thru_hole) (?:rect|roundrect|circle|oval) \(at -?[\d.]+ -?[\d.]+)\)',
                        lambda m: f'{m.group(1)} {c["rotation_deg"]:g})', fp)
        # Append net records by locating the complete balanced pad expression.
        def inject(match):
            number = match.group(1)
            name = assignments.get(f'{c["ref"]}.{number}')
            return match.group(0) + (f' (net {codes[name]} {q(name)})' if name else '')
        fp = re.sub(r'\(pad "([^"\n]+)" (?:smd|thru_hole|np_thru_hole) (?:rect|roundrect|circle|oval)', inject, fp)
        text = f' (fp_text reference {q(c["ref"])} (at 0 -4 {c["rotation_deg"]:g}) (layer "F.SilkS") (effects (font (size 0.8 0.8) (thickness 0.12))))\n (fp_text value {q(c["value"])} (at 0 4 {c["rotation_deg"]:g}) (layer "F.Fab") (effects (font (size 0.8 0.8) (thickness 0.12))))\n'
        fp = fp.rstrip()[:-1]+text+')'
        lines.append(fp)
    w,h = design['board_width_mm'],design['board_height_mm']
    for x1,y1,x2,y2 in [(0,0,w,0),(w,0,w,h),(w,h,0,h),(0,h,0,0)]:
        lines.append(f' (gr_line (start {x1:g} {y1:g}) (end {x2:g} {y2:g}) (stroke (width 0.05) (type default)) (layer "Edge.Cuts"))')
    for s in segments or []:
        lines.append(f' (segment (start {s["start"][0]:g} {s["start"][1]:g}) (end {s["end"][0]:g} {s["end"][1]:g}) (width {s["width"]:g}) (layer {q(s.get("layer","F.Cu"))}) (net {codes[s["net"]]}))')
    lines.extend([zones, ')'])
    _atomic_bytes(destination, ('\n'.join(lines)+'\n').encode('utf-8'))

def netclass_pattern(net):
    """Exact-match KiCad net class pattern: KiCad tries each pattern as an anchored regex and as a
    wildcard, so regex metacharacters allowed in net names (+ and .) are escaped."""
    return re.sub(r'([+.])', r'\\\1', net)


def project_settings(design, netclasses=None):
    """board.kicad_pro content: fabricator rules and net classes (read by pcbnew and kicad-cli DRC)."""
    from .fab_profiles import kicad_rules
    from .netclasses import resolve as resolve_netclasses
    if netclasses is None:
        netclasses = design.get('netclasses') or resolve_netclasses(design, load_catalog(), None, design.get('fabricator_profile'))[0]
    classes, patterns = [], []
    for priority, (name, spec) in enumerate(netclasses.items()):
        classes.append({'name': name, 'track_width': spec['track_mm'], 'clearance': spec['clearance_mm'],
                        'via_diameter': spec['via_dia_mm'], 'via_drill': spec['via_drill_mm'],
                        'priority': 2147483647 if name == 'Default' else priority})
        if name != 'Default':
            patterns += [{'netclass': name, 'pattern': netclass_pattern(net)} for net in spec['nets']]
    return {'meta': {'filename': 'board.kicad_pro', 'version': 3},
            'board': {'design_settings': {'rules': kicad_rules(design.get('fabricator_profile'))}},
            'net_settings': {'meta': {'version': 5}, 'classes': classes, 'netclass_assignments': {},
                             'netclass_patterns': patterns}}


def write_project(design, destination, netclasses=None):
    """Deterministic KiCad project file next to the board; replaces any copy pcbnew saved earlier."""
    _atomic_bytes(destination, (json.dumps(project_settings(design, netclasses), indent=2) + '\n').encode('utf-8'))


def write_netlist(design, path):
    root = ET.Element('export', version='D')
    components = ET.SubElement(root,'components')
    cat = load_catalog()
    for c in design['components']:
        comp = ET.SubElement(components,'comp', ref=c['ref'])
        ET.SubElement(comp,'value').text = c['value']
        ET.SubElement(comp,'footprint').text = cat[c['part_id']]['footprint']
    ns = ET.SubElement(root,'nets')
    for code,n in enumerate(design['nets'],1):
        node = ET.SubElement(ns,'net', code=str(code),name=n['name'])
        for conn in n['connections']:
            ref,pin = conn.split('.',1)
            ET.SubElement(node,'node',ref=ref,pin=pin)
    ET.indent(root)
    _atomic_bytes(path, ET.tostring(root, encoding='utf-8', xml_declaration=True))

def render_template(name, **values):
    source = (ROOT/'templates'/name).read_text()
    try:
        from jinja2 import Environment, StrictUndefined
        return Environment(undefined=StrictUndefined, autoescape=False).from_string(source).render(**values)
    except ImportError:
        for key, value in values.items():
            source = source.replace('{{ '+key+' }}',str(value))
        return source

def build_board(design, build_dir):
    build = Path(build_dir); build.mkdir(parents=True,exist_ok=True)
    src = build.parent/'src'; src.mkdir(exist_ok=True)
    # Revalidate even callers passing a handcrafted normalized design.
    auto_placed = list(design.get('auto_placed') or [])
    design = normalize_design(design['components'],design['nets'],design['board_width_mm'],design['board_height_mm'], requirements=design.get('requirements'),
                              layer_count=design.get('layer_count'), stackup=design.get('stackup'),
                              netclasses=design.get('netclass_input'), fabricator_profile=design.get('fabricator_profile'))
    design['auto_placed'] = auto_placed or design['auto_placed']
    atomic_json(build/'design.json', design)
    write_board(design,build/'board.kicad_pcb')
    write_project(design, build/'board.kicad_pro')
    (build/'board.kicad_prl').unlink(missing_ok=True)
    write_netlist(design,build/'board.net')
    progress(build.parent, 'Generating netlist with SKiDL')
    script = render_template('skidl_pcb.py.j2', design_literal=repr(design), catalog_literal=repr({pid: load_catalog()[pid] for pid in {c['part_id'] for c in design['components']}}))
    (src/'design.py').write_text(script)
    for stale in ('sim_results.json','routes.json','drc_report.json','board_3d.wrl','board_3d.glb'):
        (build/stale).unlink(missing_ok=True)
    (build.parent/'manufacturing/gerbers.zip').unlink(missing_ok=True)
    warnings = list(design['warnings'])
    backend = 'deterministic-xml'
    try:
        with tempfile.TemporaryDirectory(prefix='eea-skidl-') as cache:
            result = subprocess.run([sys.executable,str(src/'design.py')],cwd=build.parent,capture_output=True,text=True,timeout=30, env={**os.environ, 'XDG_DATA_HOME':cache, 'MPLCONFIGDIR':cache})
        if result.returncode == 0 and 'EEA_SKIDL_OK' in result.stdout:
            backend = 'skidl'
        else:
            warnings.append('SKiDL unavailable or unable to generate netlist; deterministic XML netlist used')
    except (OSError,subprocess.TimeoutExpired):
        warnings.append('SKiDL process unavailable; deterministic XML netlist used')
    if backend!='skidl':
        write_netlist(design,build/'board.net')
    from .netclasses import summary as netclass_summary
    return {'status':'success' if backend=='skidl' else 'degraded','backend':backend,'component_count':len(design['components']),'net_count':len(design['nets']),'layer_count':design['layer_count'],'stackup':design['stackup'],'fabricator_profile':design['fabricator_profile'],'netclasses':netclass_summary(design['netclasses']),'bom':design['bom'],'placement_checks':design['placement_checks'],'electrical_checks':design['electrical_checks'],'power_budget':design['power_budget'],'footprint_reviews':design['footprint_reviews'],'warnings':warnings,'auto_placed':design['auto_placed'],'artifacts':['build/board.kicad_pcb','build/board.kicad_pro','build/board.net','build/design.json'],'verified':False}
